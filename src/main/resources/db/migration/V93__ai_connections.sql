-- BACK-84 : une connexion vers un modèle. La clé ne sort pas de l'API.

CREATE TABLE back_ai_connections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider VARCHAR(64) NOT NULL,
    model VARCHAR(120) NOT NULL,
    api_key VARCHAR(500) NOT NULL
);

COMMENT ON TABLE back_ai_connections IS
    'Connexion admin vers un modèle. api_key n''est pas renvoyée par l''API.';

-- BACK-32 : qui a changé la paire d'un besoin, sans le prompt ni la réponse.

CREATE TABLE back_ai_route_changes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    besoin_code VARCHAR(64) NOT NULL,
    label VARCHAR(120) NOT NULL,
    admin_display_name VARCHAR(255) NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL,
    old_provider VARCHAR(64) NOT NULL,
    old_model VARCHAR(120) NOT NULL,
    new_provider VARCHAR(64) NOT NULL,
    new_model VARCHAR(120) NOT NULL
);

COMMENT ON TABLE back_ai_route_changes IS
    'Historique d''un changement de fournisseur ou de modèle. Désactiver un besoin n''ajoute pas de ligne.';

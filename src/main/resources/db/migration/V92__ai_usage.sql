-- BACK-31 : un appel de besoin, puis le cumul du jour UTC.
-- Pas de prompt, pas de réponse : seulement les compteurs.

CREATE TABLE back_ai_calls (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    besoin_code VARCHAR(64) NOT NULL,
    provider VARCHAR(64) NOT NULL,
    model VARCHAR(120) NOT NULL,
    prompt_tokens INTEGER NOT NULL,
    completion_tokens INTEGER NOT NULL,
    total_tokens INTEGER NOT NULL,
    usage_reported BOOLEAN NOT NULL,
    status VARCHAR(16) NOT NULL,
    duration_millis BIGINT NOT NULL,
    called_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE back_ai_usage_days (
    usage_date DATE NOT NULL,
    besoin_code VARCHAR(64) NOT NULL,
    provider VARCHAR(64) NOT NULL,
    model VARCHAR(120) NOT NULL,
    calls INTEGER NOT NULL,
    tokens INTEGER NOT NULL,
    PRIMARY KEY (usage_date, besoin_code, provider, model)
);

COMMENT ON TABLE back_ai_calls IS
    'Un appel IA d''un besoin. Le prompt et la réponse ne sont pas gardés.';
COMMENT ON TABLE back_ai_usage_days IS
    'Cumul du jour UTC par besoin, fournisseur et modèle.';
